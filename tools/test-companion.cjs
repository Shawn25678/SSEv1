const fs = require('fs'), vm=require('vm'), assert=require('node:assert/strict');
const source=fs.readFileSync('app.js','utf8');
function fn(name) { const start=source.indexOf('function '+name+'('); if(start<0)throw Error(name); const end=source.indexOf('\nfunction ',start+1); return source.slice(start,end<0?undefined:end); }
const priceContext=vm.createContext({prices:{league:'Test',tables:{Currency:[{name:'Exalted Orb',divine:.01}]},fetchedAt:1},NINJA_EXCHANGE:['Currency'],leagueId:()=> 'Test', namesMatch:(a,b)=>a.toLowerCase()===b.toLowerCase(), esc:String,formatWhen:()=> 'now',overlayBarHtml:()=>'<header></header>',dropIconHtml:()=>'',valueHtml:x=>String(x)});
vm.runInContext(fn('ninjaCurrencyPrice'),priceContext);
vm.runInContext(fn('currencyOverlayHtml').split('\nwindow.chrome')[0],priceContext);
assert.equal(priceContext.ninjaCurrencyPrice('Exalted Orb'),.01);
assert.equal(priceContext.ninjaCurrencyPrice('Missing'),null);
const html=priceContext.currencyOverlayHtml({name:'Exalted Orb',qty:20});
assert.match(html,/0.2/); assert.doesNotMatch(html,/data-quote-drop|data-price-lookup|data-open-trade/);
priceContext.prices.league='Other'; assert.equal(priceContext.ninjaCurrencyPrice('Exalted Orb'),null);
const economy=vm.createContext({});
vm.runInContext(fn('dedupeEconItems'),economy);
const normal={name:'Test unique',baseType:'Plate',divine:1,ninjaId:1,listings:20};
const upgraded={...normal,baseType:'Runemastered Plate',divine:10,ninjaId:2};
const deduped=economy.dedupeEconItems([normal,upgraded,{...upgraded,baseType:' Runemastered  Plate ',ninjaId:3,listings:30},{...upgraded,baseType:'Runeforged Plate',ninjaId:4},{...normal,corrupted:true,ninjaId:5}]);
assert.equal(deduped.length,4);
assert.equal(deduped[1].ninjaId,3);
assert.equal(deduped[1].divine,10);
assert.equal(economy.dedupeEconItems([upgraded,{...upgraded,divine:null,listings:100}])[0].divine,10);
vm.runInContext(fn('isBasicCurrency'),economy);
for(const name of ['Divine Orb','Chaos Orb','Exalted Orb']) assert.equal(economy.isBasicCurrency(name),true);
assert.equal(economy.isBasicCurrency('Greater Exalted Orb'),false);
const art={left:400,right:448,top:400,bottom:448,width:48};
const tooltip={style:{},getBoundingClientRect:()=>({width:300,height:200})};
const hover=vm.createContext({window:{innerWidth:1000,innerHeight:800}});
vm.runInContext(fn('placeItemTip'),hover);
const anchor={matches:()=>false,querySelector:()=>({getBoundingClientRect:()=>art}),getBoundingClientRect:()=>({left:0,right:1000,top:300})};
hover.placeItemTip(anchor,tooltip);
assert.equal(tooltip.style.left,'274px');assert.equal(tooltip.style.top,'192px');
art.top=20;art.bottom=68;art.left=0;
hover.placeItemTip(anchor,tooltip);
assert.equal(tooltip.style.left,'8px');assert.equal(tooltip.style.top,'76px');
console.log('Economy duplicates/variant separation and currency/artwork hover checks passed.');

const hotkeyContext=vm.createContext({state:{hotkeyLog:'F8',hotkeyNext:'F9',hotkeyPrice:'F7',hotkeyHideout:'F6'}});
for (const name of ['hotkeys','normalizeHotkey','assignHotkey']) vm.runInContext(fn(name),hotkeyContext);
assert.equal(hotkeyContext.assignHotkey('hideout','F7'),true);
assert.equal(hotkeyContext.state.hotkeyHideout,'F7');
assert.equal(hotkeyContext.state.hotkeyPrice,'F6');
assert.equal(hotkeyContext.assignHotkey('hideout','Ctrl+C'),false);
console.log('Hideout hotkey rebinding and conflict swap passed.');
